use crate::config::Resolved;
use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use std::{
    path::Path,
    process::{Command, Stdio},
};

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Container {
    pub id: String,
    pub name: String,
    pub status: String,
    pub image: String,
}

pub fn parse_list(input: &str) -> Result<Vec<Container>> {
    let mut result = Vec::new();
    for line in input.lines().filter(|l| !l.trim().is_empty()) {
        let cols: Vec<_> = line.split('|').map(str::trim).collect();
        if cols.first().is_some_and(|s| s.eq_ignore_ascii_case("ID")) {
            continue;
        }
        if cols.len() != 4 || cols[0].is_empty() || cols[1].is_empty() {
            bail!("Unexpected distrobox list output: {line}");
        }
        result.push(Container {
            id: cols[0].into(),
            name: cols[1].into(),
            status: cols[2].into(),
            image: cols[3].into(),
        });
    }
    Ok(result)
}

pub trait Backend {
    fn list(&mut self) -> Result<Vec<Container>>;
    fn create(&mut self, spec: &Resolved) -> Result<()>;
    fn remove(&mut self, name: &str) -> Result<()>;
    fn configure(&mut self, spec: &Resolved) -> Result<()>;
}

pub struct Distrobox;

pub fn capture(program: &str, args: &[String]) -> Result<String> {
    let output = Command::new(program)
        .args(args)
        .env("DBX_NON_INTERACTIVE", "1")
        .stdin(Stdio::null())
        .output()
        .with_context(|| format!("Cannot execute {program}. Is it installed on the host?"))?;
    let log = format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    if !output.status.success() {
        bail!("{program} exited with {}\n{log}", output.status);
    }
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

pub fn create_args(spec: &Resolved) -> Vec<String> {
    let mut args = vec![
        "create".into(),
        "--yes".into(),
        "--name".into(),
        spec.name.clone(),
        "--image".into(),
        spec.image.clone(),
        "--home".into(),
        spec.home.display().to_string(),
        "--volume".into(),
        format!("{0}:{0}:ro", spec.repo.display()),
        "--additional-flags".into(),
        format!(
            "--env=ACHERON_WORKSPACE={} --env=TMUX_TMPDIR=/tmp/acheron-{}",
            spec.name, spec.name
        ),
    ];
    for mount in &spec.mounts {
        args.extend([
            "--volume".into(),
            format!(
                "{}:{}:{}",
                mount.source,
                mount.target,
                if mount.read_only { "ro" } else { "rw" }
            ),
        ]);
    }
    args
}

impl Backend for Distrobox {
    fn list(&mut self) -> Result<Vec<Container>> {
        parse_list(&capture(
            "distrobox",
            &["list".into(), "--no-color".into()],
        )?)
    }
    fn create(&mut self, spec: &Resolved) -> Result<()> {
        capture("distrobox", &create_args(spec)).map(|_| ())
    }
    fn remove(&mut self, name: &str) -> Result<()> {
        capture("distrobox", &["rm".into(), "--force".into(), name.into()]).map(|_| ())
    }
    fn configure(&mut self, spec: &Resolved) -> Result<()> {
        let directory = spec.home.join(".config/acheron");
        for path in [
            spec.home.join(".config"),
            directory.clone(),
            directory.join("workspace.fish"),
        ] {
            anyhow::ensure!(
                !path.is_symlink(),
                "Refusing to write through symlink {}",
                path.display()
            );
        }
        let args = vec![
            "--no-folding".into(),
            "--restow".into(),
            "--dir".into(),
            spec.repo.join("stow").display().to_string(),
            "--target".into(),
            spec.home.display().to_string(),
            "terminal".into(),
        ];
        capture("stow", &args)?;
        std::fs::create_dir_all(&directory)?;
        let tmp = directory.join("workspace.fish.tmp");
        anyhow::ensure!(!tmp.is_symlink(), "Refusing metadata symlink");
        std::fs::write(
            &tmp,
            format!(
                "# Generated by Acheron.\nset -gx WORKSPACE_THEME {}\nset -gx ACHERON_WORKSPACE {}\n",
                spec.theme, spec.name
            ),
        )?;
        std::fs::rename(tmp, directory.join("workspace.fish"))?;
        Ok(())
    }
}

pub fn enter(name: &str) -> Result<()> {
    let status = Command::new("distrobox")
        .args(["enter", name, "--", "fish"])
        .stdin(Stdio::inherit())
        .stdout(Stdio::inherit())
        .stderr(Stdio::inherit())
        .status()?;
    anyhow::ensure!(status.success(), "distrobox enter failed: {status}");
    Ok(())
}

pub fn available(program: &str) -> bool {
    std::env::var_os("PATH").is_some_and(|p| {
        std::env::split_paths(&p).any(|dir| Path::new(&dir).join(program).is_file())
    })
}
